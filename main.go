var possibleSecondHeaderOffset = [9]int{16384, 32768, 65536, 131072, 262144, 524288, 1048576, 2097152, 4194304}

type LUKSBinaryHeader struct {
	Magic        [6]byte
	HeaderNumber uint
	Version      uint16

	// hdr size contains the size of the header with the JSON data area. The
	// offset and size of the secondary header must match this size. It is a
	// prevention to rewrite of a header with a different JSON area size
	HdrSize uint64

	// seqid is a counter (sequential number) that is always increased when a
	// new update of the header is written. The header with a higher seqid is
	// more recent and is used for recovery (if there are primary and secondary
	// headers with different seqid, the more recent one is automatically used)
	SeqId uint64

	// label is an optional label (similar to a filesystem label)
	Label        string
	CheckSumAlgo string

	// salt is generated by an RNG and is different for every header (it differs on
	// the primary and secondary header), even the backup header must contain
	// a different salt. The salt is not used after the binary header is read,
	// the main intention is to avoid deduplication of the header sector. The salt
	// must be regenerated on every header repair (but not on a regular update)
	Salt [64]byte

	// uuid is device UUID with the same format as in LUKS1
	UUID      string
	Subsystem [48]byte

	// hdr offset must match the physical header offset on the device (in bytes).
	// If it does not match, the header is misplaced and must not be used. It is a
	// prevention to partition resize or manipulation with the device start offset
	HdrOffset uint64

	// csum contains a checksum calculated with the csum alg algorithm. If the
	// checksum algorithm tag is shorter than the csum field length, the rest of
	// this field must be zeroed
	CheckSum [64]byte
}

func (h LUKSBinaryHeader) String() string {
	// Get only not null bytes from the salt
	salt := h.Salt[:]
	for i, b := range h.Salt {
		if b == 0 {
			salt = h.Salt[:i]
			break
		}
	}
	// Convert salt to base64
	saltBase64 := base64.StdEncoding.EncodeToString(salt)

	checkSum := h.CheckSum[:]
	for i, b := range h.CheckSum {
		if b == 0 {
			checkSum = h.CheckSum[:i]
			break
		}
	}
	checkSumBase64 := base64.StdEncoding.EncodeToString(checkSum)

	return fmt.Sprintf("Binary Header:\n\tHeaderNumber: %d\n\tVersion: %d\n\tHdrSize: %d\n\tSeqId: %d\n\tLabel: %s\n\tCheckSumAlgo: %s\n\tSalt: %s\n\tUUID: %s\n\tSubsystem: %s\n\tHdrOffset: %d\n\tCheckSum: %s\n",
		h.HeaderNumber, h.Version, h.HdrSize, h.SeqId, h.Label, h.CheckSumAlgo, saltBase64, h.UUID, h.Subsystem, h.HdrOffset, checkSumBase64)
}

type LUKSJSONHeader struct {
	Config   ConfigS              `json:"config"`
	Digests  map[string]DigestsS  `json:"digests"`
	KeySlots map[string]KeySlotsS `json:"keyslots"`
	Segments map[string]SegmentsS `json:"segments"`
	Tokens   map[string]TokensS   `json:"tokens"`
}

func (h LUKSJSONHeader) String() string {
	var digests string
	for k, v := range h.Digests {
		digests += fmt.Sprintf("\n\t\t\"%s\": %s,", k, v)
	}

	keySlots := ""
	for k, v := range h.KeySlots {
		keySlots += fmt.Sprintf("\n\t\t\"%s\": %s,", k, v)
	}

	segments := ""
	for k, v := range h.Segments {
		segments += fmt.Sprintf("\n\t\t\"%s\": %s,", k, v)
	}

	return fmt.Sprintf("JSON Header:\n\tConfig: %s\n\tDigests: %s\n\tKeySlots: %s\n\tSegments: %s\n\tTokens: %s\n",
		h.Config, digests, keySlots, segments, h.Tokens)
}

