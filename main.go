func mustRead(file *os.File, length int) []byte {
	data := make([]byte, length)
	_, err := file.Read(data)
	if err != nil {
		log.Fatal(fmt.Printf("Error reading file: %v", err))
	}
	return data
}

func readBinaryHeader(file *os.File, offset int64) LUKSBinaryHeader {
	// Seek to the beginning of the file
	_, err := file.Seek(offset, 0)
	if err != nil {
		fmt.Printf("Error seeking file: %v\n", err)
	}

	// Read the first 6 binary bytes from the file
	headerMagic := mustRead(file, magicLen)
	if string(headerMagic) != magic1st && string(headerMagic) != magic2nd {
		log.Println("Not a LUKS header. Magic bytes mismatch. Binary header not found")
		return LUKSBinaryHeader{}
	}

	headerRaw := InitLUKSHeaderRaw(mustRead(file, binHeaderLen-magicLen))

	res := LUKSBinaryHeader{
		Magic:        [6]byte(headerMagic),
		Version:      binary.BigEndian.Uint16(headerRaw.Read(uint16Len)),
		HdrSize:      binary.BigEndian.Uint64(headerRaw.Read(uint64Len)),
		SeqId:        binary.BigEndian.Uint64(headerRaw.Read(uint64Len)),
		Label:        string(headerRaw.Read(labelLen)),
		CheckSumAlgo: string(headerRaw.Read(cSumAlgLen)),
		Salt:         [64]byte(headerRaw.Read(saltLen)),
		UUID:         string(headerRaw.Read(uuidLen)),
		Subsystem:    [48]byte(headerRaw.Read(labelLen)),
		HdrOffset:    binary.BigEndian.Uint64(headerRaw.Skip(184).Read(uint64Len)),
		CheckSum:     [64]byte(headerRaw.Read(cSumLen)),
		HeaderNumber: 1,
	}

	if string(headerMagic) == magic2nd {
		res.HeaderNumber = 2
	}

	return res
}

func readJSONHeader(file *os.File, offset int64, hdrSize uint64) LUKSJSONHeader {
	// Seek to the beginning of the file
	_, err := file.Seek(offset, 0)
	if err != nil {
		fmt.Printf("Error seeking file: %v\n", err)
	}

	readSize := hdrSize - jsonOffset
	headerRaw := InitLUKSHeaderRaw(mustRead(file, int(readSize)))

	res := LUKSJSONHeader{}
	if err := json.Unmarshal(headerRaw.ReadUntilZeroChar(), &res); err != nil {
		// fmt.Printf("Error unmarshalling JSON header: %v\n", err)
		return res, err
		// fmt.Println("Raw JSON: ", string(headerRaw.Data))
	}

	return res, nil
}

type LUKSRawHeader struct {
	Data []byte
	Pos  int
}

func InitLUKSHeaderRaw(data []byte) LUKSRawHeader {
	return LUKSRawHeader{
		Data: data,
		Pos:  0,
	}
}

func (h *LUKSRawHeader) Read(size int) []byte {
	// Check if the size is greater than the data length
	if h.Pos+size > len(h.Data) {
		fmt.Println("Error reading header: size is greater than the data length.")
		fmt.Printf("Current Pos: %d, Size: %d, Data length: %d\n", h.Pos, size, len(h.Data))
		return []byte{}
	}
	data := h.Data[h.Pos : h.Pos+size]
	h.Pos += size
	return data
}

func (h *LUKSRawHeader) ReadUntilZeroChar() []byte {
	// Find the position of the first zero character
	zeroPos := h.Pos
	for zeroPos < len(h.Data) {
		if h.Data[zeroPos] == 0 {
			break
		}
		zeroPos++
	}
	data := h.Data[h.Pos:zeroPos]
	h.Pos = zeroPos + 1
	return data
}

func (h *LUKSRawHeader) Skip(size int) *LUKSRawHeader {
	h.Pos += size
	return h
}

func (h *LUKSRawHeader) SkipUpTo(pos int) *LUKSRawHeader {
	h.Pos = pos
	return h
}
